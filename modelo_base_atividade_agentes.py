def normalizar_acao(acao) -> Acao:
    if isinstance(acao, Acao):
        return acao
    try:
        return Acao(str(acao).upper())
    except ValueError as erro:
        raise ValueError(
            f"Ação inválida: {acao!r}. Retorne Acao.MANTER ou Acao.TROCAR."
        ) from erro


def direcao_oposta(direcao: Direcao) -> Direcao:
    return Direcao.LO if direcao == Direcao.NS else Direcao.NS


def estimar_filas_apos_acao(
    percepcao: Percepcao,
    acao: Acao,
    capacidade: int = CONFIG.capacidade_por_passo,
    verde_minimo: int = CONFIG.verde_minimo,
) -> Tuple[int, int]:
    """Estimativa de um passo, sem conhecer as próximas chegadas."""
    acao = normalizar_acao(acao)
    troca_permitida = percepcao.tempo_no_verde >= verde_minimo
    verde_estimado = percepcao.verde
    if acao == Acao.TROCAR and troca_permitida:
        verde_estimado = direcao_oposta(percepcao.verde)

    fila_ns, fila_lo = percepcao.fila_ns, percepcao.fila_lo
    if verde_estimado == Direcao.NS:
        fila_ns = max(0, fila_ns - capacidade)
    else:
        fila_lo = max(0, fila_lo - capacidade)
    return fila_ns, fila_lo

# FORNECIDO PELO PROFESSOR — execute, mas não modifique
def simular(
    agente: AgenteBase,
    cenario: CenarioTrafego,
    config: ConfiguracaoSimulacao = CONFIG,
    guardar_historico: bool = False,
) -> Tuple[Dict[str, float], pd.DataFrame]:
    """Executa um agente em um cenário de tráfego previamente gerado."""
    agente.reiniciar()
    fila_ns, fila_lo = deque(), deque()
    verde = config.verde_inicial
    tempo_no_verde = 0
    trocas = 0
    atendidos = 0
    esperas_atendidos: List[int] = []
    maior_fila_ns = maior_fila_lo = 0
    atraso_acumulado = 0
    historico = []

    for tempo in range(config.duracao):
        for _ in range(int(cenario.chegadas_ns[tempo])):
            fila_ns.append(tempo)
        for _ in range(int(cenario.chegadas_lo[tempo])):
            fila_lo.append(tempo)

        maior_fila_ns = max(maior_fila_ns, len(fila_ns))
        maior_fila_lo = max(maior_fila_lo, len(fila_lo))

        percepcao = Percepcao(
            tempo=tempo,
            fila_ns=len(fila_ns),
            fila_lo=len(fila_lo),
            verde=verde,
            tempo_no_verde=tempo_no_verde,
            espera_mais_antiga_ns=(tempo - fila_ns[0]) if fila_ns else 0,
            espera_mais_antiga_lo=(tempo - fila_lo[0]) if fila_lo else 0,
        )
        acao_solicitada = normalizar_acao(agente.decidir(percepcao))
        troca_executada = (
            acao_solicitada == Acao.TROCAR
            and tempo_no_verde >= config.verde_minimo
        )

        if troca_executada:
            verde = direcao_oposta(verde)
            trocas += 1
            tempo_no_verde = 0

        fila_aberta = fila_ns if verde == Direcao.NS else fila_lo
        for _ in range(min(config.capacidade_por_passo, len(fila_aberta))):
            chegada = fila_aberta.popleft()
            esperas_atendidos.append(tempo - chegada)
            atendidos += 1

        atraso_acumulado += len(fila_ns) + len(fila_lo)
        tempo_no_verde += 1
        maior_fila_ns = max(maior_fila_ns, len(fila_ns))
        maior_fila_lo = max(maior_fila_lo, len(fila_lo))

        if guardar_historico:
            historico.append({
                "tempo": tempo,
                "fila_ns": len(fila_ns),
                "fila_lo": len(fila_lo),
                "verde": verde.value,
                "acao_solicitada": acao_solicitada.value,
                "troca_executada": troca_executada,
                "atendidos_acumulados": atendidos,
            })

    total_chegadas = int(cenario.chegadas_ns.sum() + cenario.chegadas_lo.sum())
    fila_final = len(fila_ns) + len(fila_lo)
    assert atendidos + fila_final == total_chegadas, "Falha na conservação de veículos."

    metricas = {
        "semente": cenario.semente,
        "agente": agente.nome,
        "tempo_medio_espera": float(np.mean(esperas_atendidos)) if esperas_atendidos else 0.0,
        "maior_fila": max(maior_fila_ns, maior_fila_lo),
        "veiculos_atendidos": atendidos,
        "numero_trocas": trocas,
        "fila_final": fila_final,
        "taxa_atendimento": atendidos / total_chegadas if total_chegadas else 1.0,
        "atraso_medio_por_chegada": atraso_acumulado / total_chegadas if total_chegadas else 0.0,
        "total_chegadas": total_chegadas,
    }
    return metricas, pd.DataFrame(historico)

