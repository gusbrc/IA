# IMPLEMENTAÇÃO DO ESTUDANTE — Agente 2
class AgenteBaseadoModelo(AgenteBase):
    nome = "Baseado em modelo"

    def __init__(self, janela: int = 5, limite_fila_fechada: int = 6):
        self.janela = janela
        self.limite_fila_fechada = limite_fila_fechada
        self.reiniciar()

    def reiniciar(self) -> None:
        # Estas listas constituem parte do estado interno do agente.
        self.historico_ns: List[int] = []
        self.historico_lo: List[int] = []

    def decidir(self, percepcao: Percepcao) -> Acao:
        """Atualize o estado interno e use a evolução recente das filas.

        Uma possibilidade é calcular tendências: diferença entre valores
        recentes, média móvel ou número de passos consecutivos de crescimento.
        Sua decisão não deve depender apenas da percepção instantânea.
        """
        self.historico_lo.append(percepcao.fila_lo)
        self.historico_ns.append(percepcao.fila_ns)

        if len(self.historico_lo) > self.janela:
            self.historico_lo.pop(0)
        if len(self.historico_ns) > self.janela:
            self.historico_ns.pop(0)

        if percepcao.verde == Direcao.NS:
            historico_fechada = self.historico_lo
        else:
            historico_fechada = self.historico_ns

        media_fechada = sum(historico_fechada) / len(historico_fechada)

        tendencia_fila_fechada = historico_fechada[-1] - historico_fechada[0]

        if media_fechada > self.limite_fila_fechada:
            return Acao.TROCAR

        if media_fechada > self.limite_fila_fechada * 0.75 and tendencia_fila_fechada > 0:
            return Acao.TROCAR
        return Acao.MANTER

