# IMPLEMENTAÇÃO DO ESTUDANTE — Agente 4
class AgenteBaseadoUtilidade(AgenteBase):
    nome = "Baseado em utilidade"

    def __init__(
        self,
        peso_fila_total: float = 1.0,
        peso_maior_fila: float = 1.5,
        peso_espera: float = 2.0,
        custo_troca: float = 0.4,
        peso_desequilibrio: float = 0.7,
    ):
        self.peso_fila_total = peso_fila_total
        self.peso_maior_fila = peso_maior_fila
        self.peso_espera = peso_espera
        self.custo_troca = custo_troca
        self.peso_desequilibrio = peso_desequilibrio

    def calcular_utilidade(self, percepcao: Percepcao, acao: Acao) -> float:
        """Calcule uma pontuação: valores maiores representam melhores ações.

        Use as filas retornadas por estimar_filas_apos_acao() e combine:
        fila total, maior fila, espera mais antiga, desequilíbrio e custo da
        troca. Documente qualquer adaptação da fórmula.

        Extensão em relação à fórmula da seção 5: além de espera (E), maior
        fila (F), custo de troca (T) e desequilíbrio (D), também penaliza a
        fila total estimada (FT), evitando que o agente ignore o volume
        agregado de veículos ao comparar as duas ações.
        """
        acao = normalizar_acao(acao)
        fila_ns_est, fila_lo_est = estimar_filas_apos_acao(percepcao, acao)

        fila_total = fila_ns_est + fila_lo_est
        maior_fila = max(fila_ns_est, fila_lo_est)
        desequilibrio = abs(fila_ns_est - fila_lo_est)

        troca_efetiva = (
            acao == Acao.TROCAR and percepcao.tempo_no_verde >= CONFIG.verde_minimo
        )
        verde_estimado = direcao_oposta(percepcao.verde) if troca_efetiva else percepcao.verde
        direcao_fechada = direcao_oposta(verde_estimado)
        espera = (
            percepcao.espera_mais_antiga_ns
            if direcao_fechada == Direcao.NS
            else percepcao.espera_mais_antiga_lo
        )

        custo = self.custo_troca if troca_efetiva else 0.0

        return -(
            self.peso_fila_total * fila_total
            + self.peso_maior_fila * maior_fila
            + self.peso_espera * espera
            + self.peso_desequilibrio * desequilibrio
            + custo
        )

    def decidir(self, percepcao: Percepcao) -> Acao:
        """Escolha a ação com maior utilidade; use MANTER no empate."""
        utilidade_manter = self.calcular_utilidade(percepcao, Acao.MANTER)
        utilidade_trocar = self.calcular_utilidade(percepcao, Acao.TROCAR)
        if utilidade_trocar > utilidade_manter:
            return Acao.TROCAR
        return Acao.MANTER

