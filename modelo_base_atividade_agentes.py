# FORNECIDO PELO PROFESSOR — execute, mas não modifique
def gerar_cenario_trafego(semente: int, duracao: int = CONFIG.duracao) -> CenarioTrafego:
    """Gera chegadas reproduzíveis com três regimes de tráfego.

    1º terço: maior fluxo NS; 2º terço: maior fluxo LO;
    3º terço: fluxos equilibrados.
    """
    rng = np.random.default_rng(semente)
    corte_1, corte_2 = duracao // 3, 2 * duracao // 3

    taxa_ns = np.full(duracao, 0.45, dtype=float)
    taxa_lo = np.full(duracao, 0.45, dtype=float)
    taxa_ns[:corte_1], taxa_lo[:corte_1] = 0.65, 0.25
    taxa_ns[corte_1:corte_2], taxa_lo[corte_1:corte_2] = 0.25, 0.65

    chegadas_ns = rng.poisson(taxa_ns)
    chegadas_lo = rng.poisson(taxa_lo)
    return CenarioTrafego(semente, chegadas_ns, chegadas_lo)


def visualizar_cenario(cenario: CenarioTrafego) -> None:
    janela = 12
    ns = pd.Series(cenario.chegadas_ns).rolling(janela, min_periods=1).mean()
    lo = pd.Series(cenario.chegadas_lo).rolling(janela, min_periods=1).mean()
    plt.figure(figsize=(11, 3.5))
    plt.plot(ns, label="NS — média móvel de chegadas")
    plt.plot(lo, label="LO — média móvel de chegadas")
    plt.xlabel("Passo de tempo")
    plt.ylabel("Chegadas por passo")
    plt.title(f"Cenário de tráfego — semente {cenario.semente}")
    plt.legend()
    plt.show()


