def teste_objetivo_expresso() -> None:
    agente = AgenteBaseadoObjetivos(limite_meta=8)
    assert agente.meta_satisfeita(8, 7)
    assert not agente.meta_satisfeita(9, 2)
    # MANTER deixa LO=9; TROCAR atende LO e leva a fila a 8: somente TROCAR atinge a meta.
    p = Percepcao(10, 1, 9, Direcao.NS, 5, 0, 6)
    assert normalizar_acao(agente.decidir(p)) == Acao.TROCAR
    # As duas alternativas preservam a meta: o desempate solicitado é MANTER.
    p_empate = Percepcao(11, 2, 2, Direcao.NS, 5, 1, 1)
    assert normalizar_acao(agente.decidir(p_empate)) == Acao.MANTER


def teste_utilidade_consistente() -> None:
    agente = AgenteBaseadoUtilidade()
    p = Percepcao(15, 2, 10, Direcao.NS, 5, 1, 7)
    u_manter = agente.calcular_utilidade(p, Acao.MANTER)
    u_trocar = agente.calcular_utilidade(p, Acao.TROCAR)
    assert math.isfinite(u_manter) and math.isfinite(u_trocar)
    esperada = Acao.MANTER if u_manter >= u_trocar else Acao.TROCAR
    assert normalizar_acao(agente.decidir(p)) == esperada, (
        "decidir() deve selecionar a ação de maior utilidade."
    )


